USE ROLE SYSADMIN;
USE WAREHOUSE RIFTLAB_WH;
USE DATABASE RIFTLAB;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS MATCHES (
    PAYLOAD VARIANT,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS TIMELINES (
    PAYLOAD VARIANT,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_LTZ
);

COPY INTO MATCHES (PAYLOAD, SOURCE_FILE, LOADED_AT)
FROM (
    SELECT
        t.$1,
        METADATA$FILENAME,
        METADATA$START_SCAN_TIME
    FROM @RIOT_AZURE_STAGE/matches/ t
)
FILE_FORMAT = (FORMAT_NAME = 'RIFTLAB.RAW.RIOT_JSON')
PATTERN = '.*[.]json'
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO TIMELINES (PAYLOAD, SOURCE_FILE, LOADED_AT)
FROM (
    SELECT
        t.$1,
        METADATA$FILENAME,
        METADATA$START_SCAN_TIME
    FROM @RIOT_AZURE_STAGE/timelines/ t
)
FILE_FORMAT = (FORMAT_NAME = 'RIFTLAB.RAW.RIOT_JSON')
PATTERN = '.*[.]json'
ON_ERROR = 'ABORT_STATEMENT';
-- query pour tester si all good
SELECT
    'MATCHES' AS TABLE_NAME,
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT PAYLOAD:metadata:matchId::STRING) AS DISTINCT_MATCH_IDS,
    COUNT_IF(PAYLOAD:metadata:matchId IS NULL) AS MISSING_MATCH_IDS
FROM MATCHES

UNION ALL

SELECT
    'TIMELINES',
    COUNT(*),
    COUNT(DISTINCT PAYLOAD:metadata:matchId::STRING),
    COUNT_IF(PAYLOAD:metadata:matchId IS NULL)
FROM TIMELINES;


SELECT
    PAYLOAD:metadata:matchId::STRING AS MATCH_ID,
    SOURCE_FILE,
    LOADED_AT
FROM MATCHES
ORDER BY MATCH_ID
LIMIT 5;