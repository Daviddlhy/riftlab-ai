USE ROLE SYSADMIN;

-- Ressource de calcul
CREATE WAREHOUSE IF NOT EXISTS RIFTLAB_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Stockage logique des données
CREATE DATABASE IF NOT EXISTS RIFTLAB_DEV;
CREATE DATABASE IF NOT EXISTS RIFTLAB_PROD;
-- DEV env
CREATE SCHEMA IF NOT EXISTS RIFTLAB_DEV.RAW;
CREATE SCHEMA IF NOT EXISTS RIFTLAB_DEV.STAGING;
CREATE SCHEMA IF NOT EXISTS RIFTLAB_DEV.MART;
-- PROD env
CREATE SCHEMA IF NOT EXISTS RIFTLAB_PROD.RAW;
CREATE SCHEMA IF NOT EXISTS RIFTLAB_PROD.STAGING;
CREATE SCHEMA IF NOT EXISTS RIFTLAB_PROD.MART;

-- Contexte des prochaines requêtes
USE WAREHOUSE RIFTLAB_WH;
USE DATABASE RIFTLAB_DEV;
USE SCHEMA RAW;

-- Vérification
SELECT
    CURRENT_ROLE(),
    CURRENT_WAREHOUSE(),
    CURRENT_DATABASE(),
    CURRENT_SCHEMA();

USE ROLE ACCOUNTADMIN;
CREATE STORAGE INTEGRATION  IF NOT EXISTS  RIFTLAB_AZURE_INT
    TYPE = EXTERNAL_STAGE
    STORAGE_PROVIDER = 'AZURE'
    ENABLED = TRUE
    AZURE_TENANT_ID = '2a07b70e-5414-4f5c-b2c7-29aeeb2de7f9'
    STORAGE_ALLOWED_LOCATIONS = (
        'azure://striftlabdev01.blob.core.windows.net/riot-raw/'
    );

GRANT USAGE ON INTEGRATION RIFTLAB_AZURE_INT
    TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
USE WAREHOUSE RIFTLAB_WH;
USE DATABASE RIFTLAB_DEV;
USE SCHEMA RAW;

CREATE FILE FORMAT IF NOT EXISTS RIOT_JSON
    TYPE = JSON;

CREATE STAGE IF NOT EXISTS RIOT_AZURE_STAGE
    URL = 'azure://striftlabdev01.blob.core.windows.net/riot-raw/'
    STORAGE_INTEGRATION = RIFTLAB_AZURE_INT
    FILE_FORMAT = (
        FORMAT_NAME = 'RIFTLAB_DEV.RAW.RIOT_JSON'
    );

-- vérification du contenu
LIST @RIFTLAB_DEV.RAW.RIOT_AZURE_STAGE/matches/;

LIST @RIFTLAB_DEV.RAW.RIOT_AZURE_STAGE/timelines/;

-- query sur un fichier
SELECT
    METADATA$FILENAME AS source_file,
    t.$1:metadata:matchId::STRING AS match_id,
    t.$1 AS payload
FROM @RIFTLAB_DEV.RAW.RIOT_AZURE_STAGE/matches/ t
LIMIT 3;